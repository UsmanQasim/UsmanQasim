# Builds every profile card (light + dark, desktop + phone) and README.md.
#   python scripts/build.py            fetch fresh numbers, then draw
#   python scripts/build.py --offline  draw from scripts/state.json only (for local design work)
import json, os, sys
from datetime import date, datetime, timezone
from html import escape

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from kit import THEMES, fmt  # noqa: E402
import cards  # noqa: E402
from fetch import collect  # noqa: E402

ASSETS = os.path.join(ROOT, "assets")
STATE = os.path.join(HERE, "state.json")


def write(name, svg):
    with open(os.path.join(ASSETS, name), "w", encoding="utf8") as f:
        f.write(svg)


def picture(base, alt, width="100%", phone=True):
    a = f"assets/{base}"
    src = []
    if phone:
        src += [f'<source media="(prefers-color-scheme: dark) and (max-width: 600px)" srcset="{a}-phone-dark.svg">',
                f'<source media="(max-width: 600px)" srcset="{a}-phone-light.svg">']
    src.append(f'<source media="(prefers-color-scheme: dark)" srcset="{a}-dark.svg">')
    return f'<picture>{"".join(src)}<img src="{a}-light.svg" width="{width}" alt="{escape(alt, quote=True)}"></picture>'


def main():
    offline = "--offline" in sys.argv
    today = datetime.now(timezone.utc).date()
    P = json.load(open(os.path.join(ROOT, "profile.json"), encoding="utf8"))
    state = json.load(open(STATE, encoding="utf8")) if os.path.exists(STATE) else {}
    errors = []
    if not offline:
        state, errors = collect(P, today, state)
        with open(STATE, "w", encoding="utf8") as f:
            json.dump(state, f, indent=1, sort_keys=True)
    if "contrib" not in state:
        print("no contribution data yet:", errors)
        sys.exit(1)
    if offline:
        today = date.fromisoformat(state.get("contrib_read", today.isoformat()))

    os.makedirs(ASSETS, exist_ok=True)
    for name, t in THEMES.items():
        for phone in (False, True):
            sfx = ("-phone" if phone else "") + f"-{name}.svg"
            write("hero" + sfx, cards.hero(t, P, state, phone))
            write("github" + sfx, cards.stats(t, P, state, today, phone))
            write("heatmap" + sfx, cards.heatmap(t, P, state, today, phone))
            write("weekly" + sfx, cards.weekly(t, P, state, today, phone))
            write("whoami" + sfx, cards.whoami(t, P, state, today, phone))
            write("stack" + sfx, cards.stack(t, P, state, phone))
            write("career" + sfx, cards.career(t, P, state, phone))
            write("label-build" + sfx, cards.label(t, "What I build", f"{len(P['projects'])} projects", phone))
            write("label-stack" + sfx, cards.label(t, "Tools I reach for", "", phone))
            write("label-career" + sfx, cards.label(t, "Where I've worked", "", phone))
            for p in P["projects"]:
                write(f"project-{p['id']}" + sfx, cards.project(t, p, state, today, phone))
        for link in P["links"]:
            write(f"badge-{link['id']}-{name}.svg", cards.badge(t, link))

    C = state["contrib"]
    W = P["whoami"]
    links = "\n".join(
        f'<a href="{l["url"]}"><picture><source media="(prefers-color-scheme: dark)" srcset="assets/badge-{l["id"]}-dark.svg">'
        f'<img src="assets/badge-{l["id"]}-light.svg" height="46" alt="{escape(l["label"])}"></picture></a>' for l in P["links"])
    projects = "\n".join(
        (f'<a href="{p["url"]}">{{}}</a>' if p.get("url") else "{}").format(picture("project-" + p["id"], p["name"] + ": " + p["line"], "49%"))
        for p in P["projects"])
    years = ", ".join(f"{fmt(v)} in {k}" for k, v in sorted(C["year_totals"].items()))
    readme = f"""<!-- Generated by scripts/build.py from profile.json. Edit those, not this file. -->
<a href="{P['links'][0]['url']}">{picture("hero", f"Hi, I'm {P['name']}. {P['tagline']}")}</a>

<p align="center">
{links}
</p>

{picture("github", f"On GitHub: {fmt(C['last_year'])} contributions in the last year, current streak {C['current_streak']} days, longest streak {C['longest_streak']} days, {fmt(C['all_time'])} contributions since {P['since'][:4]}. Year by year: {years}.")}

{picture("heatmap", f"Contribution heatmap: {fmt(C['last_year'])} contributions in the last year")}

{picture("weekly", "Contributions per week over the last 16 weeks")}

{picture("whoami", f"whoami: {', '.join(W['who'])}. {W['about']} Now: " + "; ".join(W['now']))}

{picture("label-build", "What I build")}

<p align="center">
{projects}
</p>

{picture("label-stack", "Tools I reach for")}

{picture("stack", "Stack: " + "; ".join(g['group'] + ": " + ", ".join(g['items']) for g in P['stack']))}

{picture("label-career", "Where I've worked")}

{picture("career", "Career: " + "; ".join(f"{j['role']} at {j['org']} ({j['when']})" for j in P['career']))}

<p align="center"><sub>Open to senior / staff full-stack, frontend lead and AI systems roles · <a href="mailto:1998usman@gmail.com">1998usman@gmail.com</a><br>Cards redrawn every day by a GitHub Action from live GitHub data</sub></p>
"""
    with open(os.path.join(ROOT, "README.md"), "w", encoding="utf8") as f:
        f.write(readme)
    if errors:
        print("some sources failed, kept the saved copy:", *errors, sep="\n  ")
        sys.exit(1)


if __name__ == "__main__":
    main()
